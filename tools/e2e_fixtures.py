#!/usr/bin/env python3
"""Record native expectations for the end-to-end prompt fixtures.

For each prompt: tokenize it with the pinned build, wrap it in the locked chat
template, take the first tokens the pinned build chooses greedily, and render
the generated bytes through the model's own vocabulary. The result is what the
Scratch pipeline has to reproduce byte for byte.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))

from tokenizer_tables import bytes_to_unicode  # noqa: E402

PROMPTS = ('hello world', "it's 你好", '<|im_end|> hi')
GENERATE = 2


def package_vocabulary(path):
    with path.open('rb') as source:
        source.read(8)
        (length,) = struct.unpack('<Q', source.read(8))
        manifest = json.loads(source.read(length))
    return manifest['metadata']['tokenizer.ggml.tokens']['value']


def decoded_bytes(vocabulary, tokens):
    """Undo the byte-level alphabet and concatenate the pieces."""
    alphabet = {value: byte for byte, value in bytes_to_unicode().items()}
    data = bytearray()
    for token in tokens:
        for character in vocabulary[token]:
            data.append(alphabet[character])
    return bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', required=True, type=Path)
    parser.add_argument('--build', required=True, type=Path, help='directory holding the built bonsai-reference')
    parser.add_argument('--tokenize-build', type=Path, default=None,
                        help='build used for --tokenize; defaults to --build')
    parser.add_argument('--package', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--scratch', required=True, type=Path, help='directory for the intermediate logit captures')
    args = parser.parse_args()
    binary = args.build / 'bonsai-reference'
    tokenizer_binary = (args.tokenize_build or args.build) / 'bonsai-reference'
    if not binary.exists() or not tokenizer_binary.exists():
        raise SystemExit(f'missing native binary: {binary} or {tokenizer_binary}')

    def tokenize(text):
        run = subprocess.run([str(tokenizer_binary), '--tokenize', str(args.model), text],
                             capture_output=True, text=True)
        if run.returncode:
            raise SystemExit(run.stderr[-1000:])
        return [int(value) for value in run.stdout.split()]

    template = {'user': tokenize('user\n'), 'newline': tokenize('\n'), 'assistant': tokenize('assistant\n')}
    vocabulary = package_vocabulary(args.package)
    fixtures = []
    for prompt in PROMPTS:
        prompt_tokens = tokenize(prompt)
        sequence = [248045, *template['user'], *prompt_tokens, 248046,
                    *template['newline'], 248045, *template['assistant']]
        capture = args.scratch / f'prompt-{hashlib.sha256(prompt.encode()).hexdigest()[:12]}'
        subprocess.run(['rm', '-rf', str(capture)])
        run = subprocess.run([sys.executable, str(ROOT / 'tools/reference/reference.py'), 'run',
                              '--model', str(args.model), '--build', str(args.build), '--output', str(capture),
                              '--tokens', ','.join(map(str, sequence)), '--context', '64',
                              '--generate', str(GENERATE)], capture_output=True, text=True)
        if run.returncode:
            raise SystemExit(run.stderr[-2000:])
        generated = []
        for step in range(GENERATE):
            logits = capture / f'logits-{len(sequence) - 1 + step}.f32'
            values = struct.unpack(f'<{logits.stat().st_size // 4}f', logits.read_bytes())
            generated.append(max(range(len(values)), key=lambda index: (values[index], -index)))
        text = decoded_bytes(vocabulary, generated).decode('utf-8')
        fixtures.append({'prompt': prompt, 'prompt_tokens': prompt_tokens, 'template_tokens': sequence,
                         'generated': generated, 'text': text,
                         'text_sha256': hashlib.sha256(text.encode()).hexdigest()})
        print(f'{prompt!r}: {generated} -> {text!r}')
    args.output.write_text(json.dumps({'schema': 'bonsai-e2e-prompts/v1',
                                       'note': 'Native greedy tokens and their rendered bytes for the release prompts.',
                                       'generate': GENERATE, 'template': template,
                                       'prompts': fixtures}, ensure_ascii=False, indent=1) + '\n')


if __name__ == '__main__':
    main()
