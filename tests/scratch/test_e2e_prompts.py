"""End-to-end release test: typed prompts in, the expected bytes out.

Each fixture prompt is tokenized, wrapped in the locked template, prefilled and
generated by Scratch blocks alone. The expected tokens and their rendered bytes
come from the pinned native build (`tools/e2e_fixtures.py`), so a drift in the
tokenizer, the decoder, the template or the detokenizer fails here.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


@unittest.skipUnless(os.environ.get('BONSAI_TURBOWARP_VM') and os.environ.get('BONSAI_MODEL_PACKAGE'),
                     'set BONSAI_TURBOWARP_VM and BONSAI_MODEL_PACKAGE')
class EndToEndPromptTests(unittest.TestCase):
    def test_a_second_prompt_starts_from_an_empty_sequence(self):
        """Typing a new prompt must clear the KV cells, convolution history and recurrent state."""
        fixture = json.loads((ROOT / 'fixtures/native/m5/e2e-prompts.json').read_text())
        first, second = fixture['prompts'][1], fixture['prompts'][0]
        with tempfile.TemporaryDirectory() as temp:
            project = Path(temp) / 'reset.sb3'
            built = subprocess.run([sys.executable, str(ROOT / 'tools/generate_project.py'), str(project),
                                    '--text', '--benchmark'], capture_output=True, text=True)
            self.assertEqual(built.returncode, 0, built.stderr)
            env = {key: value for key, value in os.environ.items()
                   if key in ('BONSAI_TURBOWARP_VM', 'BONSAI_MODEL_PACKAGE', 'NODE_PATH')}
            env.update(BONSAI_PROMPT=first['prompt'], BONSAI_SECOND_PROMPT=second['prompt'],
                       BONSAI_SECOND_AFTER='1', BONSAI_MAX_TOKENS='2', BONSAI_LOOP='0',
                       BONSAI_STEPS=str(len(second['template_tokens']) + 2),
                       BONSAI_TIMEOUT_MS='3600000', BONSAI_DEBUG_FULL='1',
                       BONSAI_DEBUG_VARS='BS text,BS out tokens,BS prompt tokens,BS greedy token,BS step')
            run = subprocess.run(['node', str(ROOT / 'tests/scratch/run-vm.js'), str(project),
                                  '--generate', '24'], env=env, capture_output=True, text=True, timeout=3600)
            self.assertEqual(run.returncode, 0, run.stderr[-3000:])
            state = json.loads(run.stdout.strip().splitlines()[-1])
            # the second prompt was tokenized and prefilled from scratch
            self.assertEqual(state['BS prompt tokens'], second['template_tokens'])
            # one step per prompt token, plus the step that produces the first new token
            self.assertEqual(state['BS step'], len(second['template_tokens']) + 1)
            generated = state['BS out tokens'][len(second['template_tokens']):]
            self.assertEqual(generated, second['generated'])
            self.assertEqual(state['BS text'], second['text'])

    def test_generation_bound_is_clamped_to_the_kv_cache(self):
        """The cache holds 128 positions, so a 10-token prompt may generate 118 tokens."""
        fixture = json.loads((ROOT / 'fixtures/native/m5/e2e-prompts.json').read_text())
        case = fixture['prompts'][0]
        with tempfile.TemporaryDirectory() as temp:
            project = Path(temp) / 'clamp.sb3'
            built = subprocess.run([sys.executable, str(ROOT / 'tools/generate_project.py'), str(project),
                                    '--text', '--benchmark'], capture_output=True, text=True)
            self.assertEqual(built.returncode, 0, built.stderr)
            env = {key: value for key, value in os.environ.items()
                   if key in ('BONSAI_TURBOWARP_VM', 'BONSAI_MODEL_PACKAGE', 'NODE_PATH')}
            env.update(BONSAI_PROMPT=case['prompt'], BONSAI_MAX_TOKENS='128', BONSAI_STEPS='1',
                       BONSAI_LOOP='0', BONSAI_TIMEOUT_MS='600000', BONSAI_DEBUG_FULL='1',
                       BONSAI_DEBUG_VARS='BS max tokens,BS prompt length,BS decode budget,BS stop reason')
            run = subprocess.run(['node', str(ROOT / 'tests/scratch/run-vm.js'), str(project),
                                  '--generate', '24'], env=env, capture_output=True, text=True, timeout=900)
            self.assertEqual(run.returncode, 0, run.stderr[-2000:])
            state = json.loads(run.stdout.strip().splitlines()[-1])
            self.assertEqual(state['BS prompt length'], len(case['template_tokens']))
            self.assertEqual(state['BS max tokens'], 128 - len(case['template_tokens']))
            self.assertEqual(state['BS decode budget'], 127)
            self.assertEqual(state['BS stop reason'], 'context')

    def test_typed_prompts_produce_the_recorded_text(self):
        fixture = json.loads((ROOT / 'fixtures/native/m5/e2e-prompts.json').read_text())
        generate = fixture['generate']
        with tempfile.TemporaryDirectory() as temp:
            project = Path(temp) / 'release.sb3'
            built = subprocess.run([sys.executable, str(ROOT / 'tools/generate_project.py'), str(project),
                                    '--text', '--benchmark'], capture_output=True, text=True)
            self.assertEqual(built.returncode, 0, built.stderr)
            for case in fixture['prompts']:
                with self.subTest(prompt=case['prompt']):
                    env = {key: value for key, value in os.environ.items()
                           if key in ('BONSAI_TURBOWARP_VM', 'BONSAI_MODEL_PACKAGE', 'NODE_PATH')}
                    env.update(BONSAI_PROMPT=case['prompt'], BONSAI_MAX_TOKENS=str(generate),
                               BONSAI_STEPS=str(len(case['template_tokens']) + generate),
                               BONSAI_TIMEOUT_MS='3600000', BONSAI_DEBUG_FULL='1',
                               BONSAI_DEBUG_VARS='BS text,BS out tokens,BS prompt tokens')
                    run = subprocess.run(['node', str(ROOT / 'tests/scratch/run-vm.js'), str(project),
                                          '--generate', '24'], env=env, capture_output=True, text=True,
                                         timeout=3600)
                    self.assertEqual(run.returncode, 0, run.stderr[-3000:])
                    state = json.loads(run.stdout.strip().splitlines()[-1])
                    self.assertEqual(state['BS text'], case['text'], 'rendered text')
                    prompt_tokens = state['BS prompt tokens']
                    self.assertEqual(prompt_tokens, case['template_tokens'], 'templated prompt tokens')
                    generated = state['BS out tokens'][len(prompt_tokens):]
                    self.assertEqual(generated, case['generated'], 'generated token ids')
                    self.assertEqual(len(generated), generate, 'generation stops at the token bound')


if __name__ == '__main__':
    unittest.main()
